"""Regenerate the local design preview font from Windows Microsoft YaHei."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import re
import math

# Collect every Chinese character from the page source; also cover Latin UI text.
source = Path(__file__).with_name('product_ui_design.c').read_text(encoding='utf-8')
characters = sorted(set(re.findall(r'[\u4e00-\u9fff]', source)) | set(chr(i) for i in range(32, 127)), key=ord)
font = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 16)
bitmap = []
glyphs = ['    {0},']
for char in characters:
    width = max(1, math.ceil(font.getlength(char)), font.getbbox(char)[2])
    image = Image.new('L', (width, 22))
    ImageDraw.Draw(image).text((0, 0), char, font=font, fill=255)
    assert char == ' ' or image.getbbox(), f'Missing glyph: {char}'
    pixels = [value >> 4 for value in image.get_flattened_data()]
    offset = len(bitmap)
    bitmap.extend((pixels[i] << 4) | pixels[i+1] for i in range(0, len(pixels), 2))
    glyphs.append(f'    {{.bitmap_index={offset}, .adv_w={round(font.getlength(char)*16)}, .box_w={width}, .box_h=22, .ofs_x=0, .ofs_y=-5}}, /* U+{ord(char):04X} */')
start = ord(characters[0])
output = '''/* Generated by generate_design_font.py. Preview-only Chinese glyph subset. */
#include "lvgl.h"
static const uint8_t bitmap[] = {
'''
output += '\n'.join('    '+','.join(f'0x{b:02x}' for b in bitmap[i:i+16])+',' for i in range(0,len(bitmap),16))
output += '\n};\nstatic const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {\n'+'\n'.join(glyphs)+'\n};\n'
output += 'static const uint16_t unicode[] = {'+','.join(str(ord(c)-start) for c in characters)+'};\n'
output += f'''static const lv_font_fmt_txt_cmap_t cmaps[] = {{{{
    .range_start={start}, .range_length={ord(characters[-1])-start+1}, .glyph_id_start=1,
    .unicode_list=unicode, .list_length={len(characters)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}}}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps,
    .cmap_num=1, .bpp=4, .bitmap_format=0
}};
const lv_font_t design_chinese_font = {{
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height=22, .base_line=5, .dsc=&font_dsc
}};
'''
Path(__file__).with_name('design_font.c').write_text(output, encoding='utf-8')
print('Generated glyphs: '+''.join(characters))

